CREATE UNIQUE INDEX "Inventory_product_no_variant_key" ON "Inventory" ("productId") WHERE "variantId" IS NULL;
CREATE UNIQUE INDEX "Inventory_variant_key" ON "Inventory" ("variantId") WHERE "variantId" IS NOT NULL;

